    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        
        if (coaId == 0) {
            JOptionPane.showMessageDialog(this, "Please select for Update Account");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to update this record?", "Confirm", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {

        ChartOfAccountsDTO chartOfAccountsDTO = new ChartOfAccountsDTO();
        chartOfAccountsDTO.setAccount_id(coaId);
        chartOfAccountsDTO.setAccount_code(accCodeTxt.getText());
        chartOfAccountsDTO.setAccount_name(accNameTxt.getText());
        chartOfAccountsDTO.setAccount_type(accTypeCombo.getSelectedItem().toString());
        chartOfAccountsDTO.setIs_active(accStatusCombo.getSelectedItem().toString());
        
        ChartOfAccountsDAO chartOfAccountsDAO = new ChartOfAccountsDAO();
        boolean success = chartOfAccountsDAO.update(chartOfAccountsDTO);
        
        if (success) {
            loadDataSet();
            coaId = 0;
            JOptionPane.showMessageDialog(this, "Chart of Account Updated Successfully");
            
        }else{
            JOptionPane.showMessageDialog(this, "Update Failed");
        }
        }   
    }//GEN-LAST:event_jButton3ActionPerformed

