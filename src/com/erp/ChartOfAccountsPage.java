    private void saveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveBtnActionPerformed
       if (accCodeTxt.getText().trim().isEmpty() || accNameTxt.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill Code and Name!", "Warning", JOptionPane.WARNING_MESSAGE);
        return;
    }

    ChartOfAccountsDTO dto = new ChartOfAccountsDTO();
    dto.setAccount_code(accCodeTxt.getText().trim());
    dto.setAccount_name(accNameTxt.getText().trim());
    dto.setAccount_type(accTypeCombo.getSelectedItem().toString());
    dto.setIs_active(accStatusCombo.getSelectedItem().toString());

    ChartOfAccountsDAO dao = new ChartOfAccountsDAO();
    if (dao.insert(dto)) {
        JOptionPane.showMessageDialog(this, "Account Saved Successfully.");
        loadDataSet();
        clearFields();
        //showDataToTable();
    } else {
        JOptionPane.showMessageDialog(this, "Save Failed!", "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_saveBtnActionPerformed

    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
        int selectedRow = coaTable.getSelectedRow();
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Please select a row to delete!", "Warning", JOptionPane.WARNING_MESSAGE);
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this record?", "Confirm", JOptionPane.YES_NO_OPTION);
    if (confirm == JOptionPane.YES_OPTION) {
        DefaultTableModel model = (DefaultTableModel) coaTable.getModel();
        int id = Integer.parseInt(model.getValueAt(selectedRow, 0).toString());

        ChartOfAccountsDAO dao = new ChartOfAccountsDAO();
        if (dao.delete(id)) {
            JOptionPane.showMessageDialog(this, "Account Deleted.");
            loadDataSet();
           // showDataToTable();
        } else {
            JOptionPane.showMessageDialog(this, "Delete Failed!", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_deleteBtnActionPerformed
