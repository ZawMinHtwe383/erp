    private void exportExcelBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_exportExcelBtnActionPerformed
        // 🚀 EXPORT TO EXCEL FUNCTION (Apache POI သုံး၍ Excel -------> poi,poi-ooxml,poi-ooxml,xmlbeans,dom)

    javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
    fileChooser.setDialogTitle("Specify a file to save Excel");
    fileChooser.setSelectedFile(new java.io.File("ChartOfAccounts.xlsx"));
    
    int userSelection = fileChooser.showSaveDialog(this);
    if (userSelection == javax.swing.JFileChooser.APPROVE_OPTION) {
        java.io.File fileToSave = fileChooser.getSelectedFile();
        
        XSSFWorkbook workbook = new org.apache.poi.xssf.usermodel.XSSFWorkbook();
       try (java.io.FileOutputStream out = new java.io.FileOutputStream(fileToSave)) {
            
            org.apache.poi.ss.usermodel.Sheet sheet = workbook.createSheet("Chart of Accounts");
            
            // Header Row ပြုလုပ်ခြင်း
            org.apache.poi.ss.usermodel.Row headerRow = sheet.createRow(0);
            String[] columns = {"Account Code", "Account Name", "Account Type", "Status"};
            for (int i = 0; i < columns.length; i++) {
                org.apache.poi.ss.usermodel.Cell cell = headerRow.createCell(i);
                cell.setCellValue(columns[i]);
            }
            
            // JTable ထဲမှ ဒေတာများကို Loop ပတ်၍ Excel ထဲသို့ ထည့်သွင်းခြင်း
            DefaultTableModel model = (DefaultTableModel) coaTable.getModel();
            for (int i = 0; i < model.getRowCount(); i++) {
                org.apache.poi.ss.usermodel.Row row = sheet.createRow(i + 1);
                row.createCell(0).setCellValue(model.getValueAt(i, 0).toString());
                row.createCell(1).setCellValue(model.getValueAt(i, 1).toString());
                row.createCell(2).setCellValue(model.getValueAt(i, 2).toString());
                row.createCell(3).setCellValue(model.getValueAt(i, 3).toString());
            }
            
            // Auto-size columns
            for (int i = 0; i < columns.length; i++) {
                sheet.autoSizeColumn(i);
            }
            
            workbook.write(out);
            JOptionPane.showMessageDialog(this, "Excel Exported Successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Export Failed: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    }//GEN-LAST:event_exportExcelBtnActionPerformed

    private void showDataToTable() {
    DefaultTableModel model = (DefaultTableModel) coaTable.getModel();
    model.setRowCount(0); // ဇယားဟောင်းကို ရှင်းထုတ်ခြင်း
    
    ChartOfAccountsDAO dao = new ChartOfAccountsDAO();
    List<ChartOfAccountsDTO> list = dao.getAllAccounts();
    
    for (ChartOfAccountsDTO dto : list) {
        model.addRow(new Object[]{
            dto.getAccount_id(),
            dto.getAccount_code(),
            dto.getAccount_name(),
            dto.getAccount_type(),
             dto.getIs_active()
                
        });
    }
    }

